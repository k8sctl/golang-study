package main

import "fmt"

/*
- 포인터(pointer)는 "메모리 주소"를 저장하는 타입이다.
- p = &a 는 변수 a의 주소를 포인터 변수 p에 저장한다.
- *p 는 p가 가리키는 주소에 들어있는 실제 값(역참조)이다.
- 따라서 *p = 100 으로 값을 바꾸면, a 자체의 값도 100으로 변경된다.
- 즉, 포인터를 통해 원본 변수의 값을 직접 수정할 수 있다.
*/

func main() {
	var a int = 500
	var p *int

	p = &a

	fmt.Printf("p의 값: %p\n", p)
	fmt.Printf("p가 가리키는 메모리의 값: %dn", *p)

	*p = 100
	fmt.Printf("a의 값: %d\n", a)
}

/*
[출력 결과]
p의 값: 0xc000018050 (a의 메모리 주소를 16진수로 표현)
p가 가리키는 메모리의 값: 500
a의 값: 100
*/
