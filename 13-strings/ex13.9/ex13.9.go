package main

import "fmt"

func main() {
	str := "Hello 월드"

	for _, v := range str {
		fmt.Printf("타입:%T 값:%d 문자값:%c\n", v, v, v)
	}
}

/*
[코드 설명]
- for range로 문자열을 순회하면 Go는 문자열을 UTF-8 기준으로 해석해서
  "문자(정확히는 rune, 유니코드 코드포인트)" 단위로 값을 꺼내준다.
- v의 타입은 rune(int32)이며, v에는 각 문자의 코드포인트 값이 들어간다.
- 따라서 한글도 깨지지 않고 정상적으로 출력된다.
- (참고) range의 첫 번째 값은 바이트 인덱스이며, 여기서는 '_'로 버렸다.
*/

