package main

import "fmt"

func main() {
	str := "Hello 월드"
	arr := []rune(str) // []rune 슬라이스로 타입 변환 후 한 글자씩 순회
	// 슬라이스는 동적 배열이라고 생각하면 된다?
	// rune -> int32의 별칭 타입

	for i := 0; i < len(arr); i++ {
		fmt.Printf("타입:%T 값:%d 문자값:%c\n", arr[i], arr[i], arr[i])
	}
}

/*
[코드 설명]
- str := "Hello 월드" 는 UTF-8로 인코딩된 문자열이다.
- []rune(str)는 문자열을 '유니코드 코드포인트 단위'로 변환한다.
  즉, 바이트(byte) 단위가 아니라 '문자(정확히는 rune)' 단위로 쪼개진다.
- rune는 int32의 별칭 타입이며, 한 글자의 유니코드 값(코드포인트)을 담는다.
- 따라서 len(arr)는 문자 개수(코드포인트 개수)가 되고,
  arr[i]는 i번째 문자의 코드포인트 값이 된다.
- fmt.Printf에서
  - %T : 타입 출력 (rune)
  - %d : 코드포인트 정수값 출력
  - %c : 코드포인트를 문자로 출력
  -> 한글도 깨지지 않고 정상적으로 출력된다.

[참고: 슬라이스]
- 슬라이스([]T)는 동적 배열처럼 쓸 수 있는 자료구조다.
  길이(len)와 용량(cap)을 가지고, 배열 위에 얹힌 뷰(view)처럼 동작한다.
  (그래서 그냥 '동적 배열'로 생각해도 학습 단계에서는 충분하다.)
*/

