package main

import "fmt"

func main() {
	poet1 := "죽는 날까지 하늘을 우러러\n한 점 부끄럼이 없기를,\n잎새에 이는 바람에도\n나는 괴로워했다.\n"

	poet2 := `죽는 날까지 하늘을 우러러
한 점 부끄럼이 없기를,
잎새에 이는 바람에도
나는 괴로워했다.`

	fmt.Println(poet1)
	fmt.Println(poet2)
}

/*
[코드 설명]
- Go 문자열 리터럴에는 2가지가 있다.

1) 해석 문자열(일반 문자열) "..."
- \n, \t 같은 이스케이프 시퀀스를 해석한다.
- poet1은 "\n"을 줄바꿈으로 처리해 여러 줄 문자열을 만든다.
- 마지막에 "\n"이 한 번 더 있어서 출력 후 줄이 한 줄 더 내려간다.

2) 원시 문자열(raw string) `...`
- 백틱(`)으로 감싸며, 이스케이프 시퀀스를 해석하지 않는다.
- 입력한 그대로(줄바꿈/공백/탭 포함) 문자열이 저장된다.
- poet2는 코드에 작성한 줄바꿈이 그대로 출력된다.
  (주의: 둘째 줄부터 앞에 들여쓰기(탭/공백)를 넣으면 그 들여쓰기까지 함께 출력된다.)
*/

