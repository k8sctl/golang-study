package main

const Y int = 3 // 상수: 컴파일 시점에 값이 확정됨

/*
배열 선언 규칙
- 배열 타입의 길이([N]T에서 N)는 컴파일 시점에 확정 가능해야 한다.
- 따라서 변수(x)는 배열 길이로 사용할 수 없고, 상수(const)는 사용할 수 있다.
*/

func main() {
	x := 5 // 변수: 런타임 값

	// 배열 길이에 변수 x를 사용하면 컴파일 에러
	// a := [x]int{1, 2, 3, 4, 5}
	_ = x // 미사용 경고 방지

	// 상수 Y는 배열 길이로 사용 가능
	b := [Y]int{1, 2, 3}
	_ = b // 미사용 경고 방지

	// 리터럴 상수(10)도 배열 길이로 사용 가능
	var c [10]int // int의 기본값(0)으로 초기화
	_ = c         // 미사용 경고 방지
}
