package main

import (
	"fmt"
	"math/rand"
)

func main() {
	fmt.Println(rand.Int())
}

/*
[코드 설명]
- math/rand 패키지의 rand.Int()를 호출해 int 난수 1개를 출력하는 예제다.
- rand.Int()는 "전역 난수 생성기"에서 값을 뽑는다.
- 이 코드에는 시드(seed) 설정이 없어서, 프로그램을 다시 실행해도
  난수의 "순서"가 항상 동일하게 시작한다(진짜 랜덤처럼 보이지 않을 수 있음).
  실행할 때마다 다른 난수를 원하면 보통 rand.Seed(time.Now().UnixNano()) 같은 시드 초기화가 필요하다.

[출력 결과]
- 정수 1개가 출력된다. (예: 5577006791947779410)
- 시드를 설정하지 않으면 실행할 때마다 같은 값(또는 같은 순서)로 출력되는 경우가 많다.
*/
