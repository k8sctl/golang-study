package main

import (
	"fmt"
)

func main() {
	for i := 0; i < 10; i++ {
		if i == 3 {
			continue // 후처리식으로 이동한다.
		}
		if i == 6 {
			break // 반복문을 빠져나간다.
		}
		fmt.Println("6 *", i, "=", 6*i)
	}
}

/*
	[출력 결과]
	6 * 0 = 0
	6 * 1 = 6
	6 * 2 = 12
	6 * 4 = 24
	6 * 5 = 30

	i == 3일 때:
	continue로 인해 현재 반복의 남은 코드를 건너뛰고 후처리식(i++)으로 이동한다.
	따라서 i == 3일 때는 출력되지 않는다.

	i == 6일 때:
	break가 실행되어 반복문이 즉시 종료된다.
	따라서 i == 7, 8, 9는 도달하지 않는다.
*/
